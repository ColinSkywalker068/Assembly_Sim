"""The DexAgent checkout the CRX + YAM port runs in: a fresh clone of the pinned commit, the port patch
(patches/0001-crx-yam-port.patch, code only) applied, and setup/ replaced by this bench (scene.install_bench).

`write_patch` exports the patch from a development clone whose history starts at the pinned commit: every change
outside setup/ (the bench there is generated, never patched). `prepare_checkout` builds a trial's checkout and
`verify_checkout` checks one: HEAD at the commit, the working tree outside setup/ differing from it by exactly the
patch, nothing untracked or ignored there (stale bytecode would run instead of the verified sources; run Python with
-B), and setup/ holding exactly the bench this code generates for the given S0 limits.
"""
from __future__ import annotations

import hashlib
import os
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from ..export import DEXAGENT_COMMIT
from . import scene

PATCH = Path(__file__).resolve().parents[1] / 'patches' / '0001-crx-yam-port.patch'
EXCLUDE_SETUP = ':(exclude)setup'
# Fixed so that the comparison with the patch does not depend on the user's git configuration (as aspire/checkout.py).
DIFF_OPTIONS = ('--no-color', '--no-ext-diff', '--no-renames', '--no-relative', '--full-index', '--src-prefix=a/',
                '--dst-prefix=b/', '--unified=3', '--inter-hunk-context=0', '--diff-algorithm=myers',
                '--indent-heuristic')
HEADER = ('DexAgent e29bdad ported to the CRX + YAM bench (tasks/dual_arm_crag_skull/baselines/dexagent/README.md, "Port '
          'to the shared hardware").\nGenerated by bench/checkout.write_patch from the development clone; setup/ is '
          'not part of it (bench/scene.install_bench writes it).\n\n')


@dataclass(frozen=True)
class PreparedCheckout:
    path: Path
    commit: str
    patch_sha256: str
    bench_sha256: str


def _git(*args, cwd=None):
    environment = {key: value for key, value in os.environ.items() if not key.startswith('GIT_')}
    environment.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM='1', GIT_TERMINAL_PROMPT='0')
    result = subprocess.run(['git', *args], cwd=cwd, capture_output=True, text=True, env=environment, check=False)
    if result.returncode:
        raise RuntimeError(f"git {' '.join(args)} failed with exit code {result.returncode}: {result.stderr.strip()}")
    return result.stdout


def patch_body(patch=PATCH):
    """The patch from its first `diff --git` line on (git apply ignores the header before it)."""
    text = Path(patch).read_text()
    start = text.find('diff --git ')
    if start < 0 or (start > 0 and text[start - 1] != '\n'):
        raise ValueError(f'{patch} contains no git diff')
    return text[start:]


def write_patch(dev_clone, patch=PATCH, commit=DEXAGENT_COMMIT):
    """Export the port patch from a development clone (every committed and uncommitted change outside setup/)."""
    diff = _git('-C', str(dev_clone), 'diff', *DIFF_OPTIONS, commit, '--', '.', EXCLUDE_SETUP)
    if not diff.strip():
        raise ValueError(f'{dev_clone} has no changes outside setup/ against {commit}')
    Path(patch).parent.mkdir(parents=True, exist_ok=True)
    Path(patch).write_text(HEADER + diff)
    return Path(patch)


def tree_digest(folder):
    """sha256 over every file under `folder` (relative path and content), in path order."""
    digest = hashlib.sha256()
    folder = Path(folder)
    for path in sorted(p for p in folder.rglob('*') if p.is_file()):
        digest.update(str(path.relative_to(folder)).encode() + b'\0' + hashlib.sha256(path.read_bytes()).digest())
    return digest.hexdigest()


def bench_digest(s0_limits):
    """The digest of the bench this code generates for `s0_limits` (written to a temporary folder)."""
    with tempfile.TemporaryDirectory() as folder:
        scene.write_bench(Path(folder), s0_limits)
        (Path(folder) / 'README.md').write_text(scene.BENCH_README)
        return tree_digest(folder)


def verify_checkout(path, s0_limits, commit=DEXAGENT_COMMIT, patch=PATCH):
    """Raise unless `path` is the port's checkout (module docstring); return its PreparedCheckout."""
    path = Path(path).resolve()
    head = _git('-C', str(path), 'rev-parse', 'HEAD').strip()
    if head != commit:
        raise ValueError(f'{path} is at {head}, expected {commit}')
    if _git('-C', str(path), 'diff', *DIFF_OPTIONS, 'HEAD', '--', '.', EXCLUDE_SETUP) != patch_body(patch):
        raise ValueError(f'{path} does not differ from {commit} by exactly {Path(patch).name} outside setup/')
    untracked = [entry for entry in _git('-C', str(path), 'ls-files', '--others', '--exclude-standard').splitlines()
                 if not entry.startswith('setup/')]
    ignored = [entry for entry in _git('-C', str(path), 'ls-files', '--others', '--ignored', '--exclude-standard',
                                       '--directory').splitlines() if not entry.startswith('setup/')]
    if untracked or ignored:
        raise ValueError(f'{path} has files outside the patch: {(untracked + ignored)[:5]} (run Python with -B)')
    found, expected = tree_digest(path / 'setup'), bench_digest(s0_limits)
    if found != expected:
        raise ValueError(f'{path}/setup is not the bench generated for these S0 limits')
    return PreparedCheckout(path, commit, hashlib.sha256(Path(patch).read_bytes()).hexdigest(), found)


def prepare_checkout(source, destination, s0_limits, commit=DEXAGENT_COMMIT, patch=PATCH):
    """A new checkout at `destination` (absent or empty): clone `source` (only read), detach at `commit`, apply the
    patch, install the bench; verified."""
    destination = Path(destination)
    if destination.exists() and any(destination.iterdir()):
        raise ValueError(f'{destination} is not empty')
    _git('clone', '--quiet', '--no-checkout', str(source), str(destination))
    _git('-C', str(destination), '-c', 'advice.detachedHead=false', 'checkout', '--quiet', '--detach', commit)
    body = patch_body(patch)
    with tempfile.NamedTemporaryFile('w', suffix='.patch', delete=False) as handle:
        handle.write(body)
    try:
        # --index: the files the patch adds are then tracked, so `git diff HEAD` shows them like every other change
        _git('-C', str(destination), 'apply', '--index', '--check', handle.name)
        _git('-C', str(destination), 'apply', '--index', handle.name)
    finally:
        os.unlink(handle.name)
    scene.install_bench(destination, s0_limits)
    return verify_checkout(destination, s0_limits, commit, patch)
